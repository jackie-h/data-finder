"""
Test specifications for the TPC-BiH benchmark (Kaufmann et al., "TPC-BiH: A Benchmark for Bitemporal Databases", TPCTC 2013):
the finder route of each benchmark case.

A case (tpch_bih_cases.py) holds the SQL of tpch_bih_definitions.py or tpch_definitions.py, the values of its parameters and the rows that SQL returns on
the generated data (tpch_bih_expected.py, generated). tpch_bih_queries.py has the finder query for it,
or the reason the finders cannot ask it as the report does, which makes the spec a skip. The SQL route, which runs the report's
SQL itself, is in the backend's test.

Schema (the TPC-H tables; comment columns and a few descriptive ones are left out):

    region, nation   not versioned
    supplier         degenerate: system time only
    customer         bitemporal, application time visible_time
    part             bitemporal, application time availability_time
    partsupp         bitemporal, application time validity_time
    orders           bitemporal, active_time as application time, receivable_time as ordinary dates
    lineitem         bitemporal, application time active_time

The data is generated by tpch_bih_generator.py, which follows Appendix A of the report, at scale factor 0.001 with 1000 scenarios
and seed 1 (tpch_bih_data.py).
"""
from types import SimpleNamespace

import numpy as np

from datafinder_examples_tests.spec import TestExpectation
from datafinder_examples_tests.tpch_bih_case import BenchmarkCase
from datafinder_examples_tests.tpch_bih_cases import CASES
from datafinder_examples_tests.tpch_bih_queries import QUERIES, Unsupported

TPCH_BIH_MAPPING = "tpch_bih_mapping.md"

_BACKENDS = ("duckdb",)


def _unsupported(case: BenchmarkCase, reason: str) -> TestExpectation:
    """A case whose query the finders cannot ask as the report does: skipped with the reason, so the gap stays visible."""
    def query(_finder):
        raise NotImplementedError(reason)
    return TestExpectation(
        name=case.id,
        query=query,
        expected_columns=[str(column) for column in case.select],
        expected_result=np.empty((0, len(case.select)), dtype=object),
        skip_backends={backend: reason for backend in _BACKENDS},
    )


def _finder_expectation(case: BenchmarkCase) -> TestExpectation:
    """The finder route of a benchmark case: its query, asked with the case's parameters, returns the case's expected rows."""
    entry = QUERIES[case.id]
    if isinstance(entry, Unsupported):
        return _unsupported(case, entry.reason)
    parameters = SimpleNamespace(**case.parameters)
    return TestExpectation(
        name=case.id,
        query=lambda q: entry.query(q, parameters),
        expected_columns=entry.columns,
        expected_result=case.expected(),
        approximate=case.approximate,
    )


#: every benchmark case, in the order of the report: B.1 time travel (T), B.2 (H.1 and the TPC-H queries Q), B.3 key history
#: (K), B.4 range (R) and B.5 bitemporal (B5)
ALL_TPCH_BIH_CASES = [_finder_expectation(case) for case in CASES.values()]
